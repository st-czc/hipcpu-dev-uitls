#!/usr/bin/env python3
"""Generate rocblas_stubs.cpp.

Each public BLAS function returns rocblas_status_not_implemented.
The framework functions keep their real definitions.
"""
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent  # hipcpu-dev-utils/hipblas-cpu
REPO_ROOT = SCRIPT_DIR.parents[1]  # checkout root

ROCBLAS_ROOT = REPO_ROOT / "rocm-libraries" / "projects" / "rocblas"
FUNCTIONS_HEADER = ROCBLAS_ROOT / "library" / "include" / "internal" / "rocblas-functions.h"
KEPT_SOURCES = [
    ROCBLAS_ROOT / "library/src/rocblas_auxiliary.cpp",
    ROCBLAS_ROOT / "library/src/handle.cpp",
    ROCBLAS_ROOT / "library/src/logging.cpp",
    ROCBLAS_ROOT / "library/src/rocblas_ostream.cpp",
    ROCBLAS_ROOT / "library/src/buildinfo.cpp",
    ROCBLAS_ROOT / "library/src/utility.cpp",
]
OUT = SCRIPT_DIR / "rocblas_stubs.cpp"

DEFAULTS = {
    "rocblas_status": "rocblas_status_not_implemented",
    "bool": "false",
    "void": None,
}

# Skip functions that the kept sources already define.
# Over-matching is safe. The kept sources do not call BLAS math functions.
kept = set()
for src in KEPT_SOURCES:
    for name in re.findall(r"\brocblas_[a-zA-Z0-9_]+(?=\s*\()", src.read_text()):
        kept.add(name)

# axpy kernel sources use a macro, so list their function names here.
kept.update({"rocblas_haxpy", "rocblas_saxpy", "rocblas_daxpy", "rocblas_caxpy", "rocblas_zaxpy"})
# GEMM is implemented in blas3/rocblas_gemm_host.cpp (OpenBLAS-backed).
kept.update({"rocblas_sgemm", "rocblas_dgemm", "rocblas_cgemm", "rocblas_zgemm"})

text = FUNCTIONS_HEADER.read_text()
pat = re.compile(r"ROCBLAS_EXPORT\s+(.*?)\s*;", re.DOTALL)

stubs = []
seen = set()
skipped = []
for body in pat.findall(text):
    m = re.search(r"(rocblas_[a-zA-Z0-9_]+)\s*\(", body)
    if not m:
        sys.exit(f"cannot locate function name in: {body!r}")
    name = m.group(1)
    ret = " ".join(body[: m.start(1)].split())
    sig = " ".join(body[m.start(1) :].split())
    if name in kept:
        skipped.append(name)
        continue
    if ret not in DEFAULTS:
        sys.exit(f"unexpected return type {ret!r} for {name} (add it to DEFAULTS or exclude it)")
    if sig in seen:
        continue
    seen.add(sig)
    default = DEFAULTS[ret]
    body_lines = f"    return {default};" if default is not None else ""
    stubs.append(f"{ret} {sig}\n{{\n{body_lines}\n}}")

header = """// Generated by gen_rocblas_stubs.py. Do not edit.
// Each BLAS math function returns rocblas_status_not_implemented.
// The framework functions keep their real definitions.
#include "rocblas/rocblas.h"

extern "C" {
"""

OUT.write_text(header + "\n\n".join(stubs) + "\n\n} // extern \"C\"\n")
print(f"wrote {len(seen)} stubs (skipped {len(skipped)} framework functions) to {OUT}")
